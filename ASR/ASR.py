def plot_dist(ax, dist, title, panel_label):
    items = dist.most_common(10)
    if not items:
        return

    labels, vals = zip(*items)
    colors = [AA_COLORS.get(a, '#999') for a in labels]

    ax.bar(labels, vals, color=colors, edgecolor='black')
    ax.grid(axis='y', linestyle='--', alpha=0.3)

    style_ax(ax, title, "AA", "Count", panel_label)

