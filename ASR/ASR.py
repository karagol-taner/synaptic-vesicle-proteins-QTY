# 5.  Subtree amino-acid composition after each divergence node
# ──────────────────────────────────────────────────────────────────────────────
def subtree_leaf_aas(node, col):
    aas = []
    for leaf in node.get_leaves():
        aa = seq_dict.get(leaf.name, '-')[col]
        if aa not in GAPS:
            aas.append(aa)
    return aas


# Aggregate for T-divergence vs V-divergence
