v_cols = div_df[div_df.diverge_aa == 'V']['col_1based'].values - 1

def aa_dist(cols, node_filter_aa):
    """Leaf aa distribution for columns where diverge_aa == node_filter_aa."""
    counter = Counter()
    for col in cols:
        # find the node where divergence first happens
        rows = div_df[(div_df.col_1based == col+1) &
                      (div_df.diverge_aa == node_filter_aa)]
        if rows.empty:
            continue
        for _, row in rows.iterrows():
            node_name = row["diverge_node"]
            results   = tree.search_nodes(name=node_name)
            node_obj  = results[0] if results else None
            if node_obj is None:
                continue
            counter.update(subtree_leaf_aas(node_obj, col))
    return counter

t_dist = aa_dist(t_cols, 'T')
v_dist = aa_dist(v_cols, 'V')

