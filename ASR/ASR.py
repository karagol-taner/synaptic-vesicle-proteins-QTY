# ──────────────────────────────────────────────────────────────────────────────
# 4.  For each Ala column: find the earliest divergence to T or V
#     "divergence node" = deepest node (closest to root) that carries T or V
# ──────────────────────────────────────────────────────────────────────────────
TARGET = {'T', 'V'}

def depth_of(node):
    d = 0
    n = node
    while n.up:
        d += 1
        n = n.up
    return d


records = []
for col in ala_cols:
    for target_aa in TARGET:
        # Walk postorder; find the one with smallest depth that shows target_aa
        earliest = None
        earliest_depth = 9999
        for node in tree.traverse("preorder"):
            if node_states[node.name][col] == target_aa:
                d = depth_of(node)
                if d < earliest_depth:
                    earliest_depth = d
                    earliest        = node
        if earliest is None:
            continue

        # Determine if Input_seq is in the T or V subtree
        inp_aa        = inp_states[col]
        inp_in_target = (inp_aa == target_aa)

        records.append({
            "col_1based"    : col + 1,
            "root_aa"       : 'A',
            "diverge_aa"    : target_aa,
            "diverge_node"  : earliest.name,
            "diverge_depth" : earliest_depth,
            "inp_aa"        : inp_aa if inp_aa not in GAPS else 'gap',
            "inp_matches_div": inp_in_target,
        })

div_df = pd.DataFrame(records)
