"""
Ancestral Sequence Reconstruction — "Alanine-Centric" Model
============================================================
Reconstructs ancestral amino acid states at every internal node of the
phylogenetic tree using Fitch parsimony, then focuses specifically on
positions where the deepest shared ancestor carries Alanine (A) and
traces how those positions diverge to Threonine (T) or Valine (V) in
daughter lineages, with special attention to the Input_seq_ATOM_A clade.

Outputs
-------
1. ancestral_ala_analysis.png  – multi-panel figure
2. ala_divergence_table.csv    – per-position divergence summary
3. per_node_asr.csv            – full ancestral state table (all nodes × sites)
"""

