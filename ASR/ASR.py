# ──────────────────────────────────────────────────────────────────────────────
# 2.  Fitch Parsimony — ancestral reconstruction
# ──────────────────────────────────────────────────────────────────────────────
GAPS = {'-', 'X', '?', 'B', 'Z'}

def fitch_up(node, col_idx):
    """Bottom-up pass: returns the Fitch set and parsimony score."""
    if node.is_leaf():
        aa = seq_dict.get(node.name, '-')[col_idx]
        node._fitch_set = {aa} if aa not in GAPS else set()
        node._fitch_score = 0
        return node._fitch_set, 0

    child_sets, child_scores = [], []
    for child in node.children:
        cs, sc = fitch_up(child, col_idx)
        child_sets.append(cs)
        child_scores.append(sc)

    total_score = sum(child_scores)
    intersection = child_sets[0].copy()
    for cs in child_sets[1:]:
        intersection &= cs

    if intersection:
        node._fitch_set   = intersection
        node._fitch_score = 0
    else:
        union = set()
        for cs in child_sets:
            union |= cs
        node._fitch_set   = union
        node._fitch_score = 1

    node._fitch_score += total_score
    return node._fitch_set, node._fitch_score


def fitch_down(node, parent_state=None):
    """Top-down pass: select a single state from the Fitch set."""
    fset = node._fitch_set
    if not fset:                       # gap/unknown — inherit or mark '?'
        node._anc_state = parent_state if parent_state else '?'
    elif parent_state and parent_state in fset:
        node._anc_state = parent_state
    else:
        # Prefer A > T > V > alphabetical for the Ala-centric analysis
        for pref in ['A', 'T', 'V']:
            if pref in fset:
                node._anc_state = pref
                break
        else:
            node._anc_state = sorted(fset)[0]

    for child in node.children:
        fitch_down(child, node._anc_state)


print("Running Fitch parsimony across all alignment columns …")
node_states = {}          # node.name → list of states, length = aln_len
for node in tree.traverse():
    node_states[node.name] = ['?'] * aln_len

for col in range(aln_len):
    fitch_up(tree, col)
    fitch_down(tree, None)
    for node in tree.traverse():
        node_states[node.name][col] = node._anc_state

